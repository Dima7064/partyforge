const FALLBACK_NAMES = [
  "Кайрен", "Мира", "Торн", "Элара", "Гарат", "Лиан",
  "Сора", "Дариус", "Нэрис", "Бран", "Вела", "Ксав",
];

export function pickName(race: RaceRow, rng: Rng): string {
  const pool = NAMES_BY_RACE[race.name] ?? FALLBACK_NAMES;
  return pool[Math.floor(rng() * pool.length)];
}

export function pickUniqueName(
  race: RaceRow,
  rng: Rng,
  used: Set<string>,
  maxAttempts = 20,
): string {
  for (let i = 0; i < maxAttempts; i++) {
    const name = pickName(race, rng);
    if (!used.has(name)) {
      used.add(name);
      return name;
    }
  }
  const base = pickName(race, rng);
  let suffix = 2;
  while (used.has(`${base} ${suffix}`)) suffix++;
  const name = `${base} ${suffix}`;
  used.add(name);
  return name;
}